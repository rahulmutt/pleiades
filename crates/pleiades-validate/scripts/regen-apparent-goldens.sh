#!/usr/bin/env bash
# Regenerate apparent-of-date goldens from JPL Horizons (quantity 31, ObsEcLon:
# apparent ecliptic longitude referred to the IAU76/80 ecliptic-of-date, with
# light-time, gravitational deflection, and stellar aberrations),
# geocentric observer (500@399), epochs tagged TT (TIME_TYPE=TT). Run manually
# when refreshing the corpus.
#
# Tolerances: per-body, each = max observed residual + 2 arcsec, rounded up to 0.1"
# (FU-14, 2026-09-30; see the TOLERANCE RATIONALE block echoed below): 2.2" for every
# body except Uranus (2.3"). Measured maxima are 0.11"-0.25", the packaged-ephemeris
# fit floor. Before FU-14 the goldens were fetched without TIME_TYPE=TT, so Horizons
# read TLIST as UT while the gate evaluated the rows as TT; that dT-sized offset
# (about 38" for the Moon at 2050) was what the former 40.8" Moon tolerance absorbed.
# 433-Eros is EXCLUDED: the light-time iteration diverges or goes out of range at most
# epochs because Eros's packaged data span is too narrow for apparent-mode convergence.
set -euo pipefail
OUT="$(dirname "$0")/../data/apparent-goldens.csv"
API="https://ssd.jpl.nasa.gov/api/horizons.api"
EPOCHS="2415025.5 2433282.5 2451545.0 2469807.5 2488065.5" # ~1900,1950,2000,2050,~2100 (JD)
# NOTE: 2415025.5 = 1900-Jan-06 (5 days past the packaged-backend start 2415020.5, to
# avoid apparent light-time iteration stepping before coverage); 2488065.5 = 2099-Dec-26
# (4 days before coverage end 2488069.5, same reason). Interior epochs 1950/2000/2050
# are well clear of the boundaries.
# body label -> Horizons COMMAND code (Eros excluded; see script header)
BODIES="Sun:10 Moon:301 Mercury:199 Venus:299 Mars:499 Jupiter:599 Saturn:699 Uranus:799 Neptune:899 Pluto:999"

# Fetch one Horizons row for COMMAND=$1 at TLIST=$2 (JD, TT) with QUANTITIES=$3, and
# print the $$SOE..$$EOE data line. TIME_TYPE=TT makes Horizons read TLIST as TT, which
# is how the gate evaluates the row (jd_tt). Without it Horizons reads TLIST as UT and
# the goldens carry a dT-sized offset (about 38" for the Moon at 2050; FU-14). The
# header check refuses to write UT-tagged goldens if that ever regresses.
fetch_tt() {
  local text
  text=$(curl -sS -m 30 "$API?format=text&COMMAND='$1'&EPHEM_TYPE=OBSERVER&CENTER='500@399'&TLIST='$2'&TIME_TYPE=TT&QUANTITIES='$3'&ANG_FORMAT=DEG&CAL_FORMAT=JD&extra_prec=YES")
  if ! grep -q 'Date_________JDTT' <<<"$text"; then
    echo "Horizons did not tag COMMAND=$1 TLIST=$2 as TT (no Date_________JDTT header); refusing to write UT-tagged goldens" >&2
    return 1
  fi
  sed -n '/\$\$SOE/,/\$\$EOE/p' <<<"$text" | sed '1d;$d'
}
{
  echo "# Source: JPL Horizons API ($API), EPHEM_TYPE=OBSERVER, CENTER='500@399', TIME_TYPE=TT,"
  echo "# QUANTITIES='31' (ObsEcLon, apparent ecliptic longitude referred to the IAU76/80 ecliptic-of-date,"
  echo "# with light-time, gravitational deflection, and stellar aberrations), ANG_FORMAT=DEG, extra_prec=YES."
  echo "# Regenerated by crates/pleiades-validate/scripts/regen-apparent-goldens.sh"
  echo "#"
  echo "# TOLERANCE RATIONALE (per-body model limits):"
  echo "#   - Epoch tag: TLIST is passed with TIME_TYPE=TT, so Horizons evaluates each row at the"
  echo "#     same TT instant the gate uses (jd_tt). Goldens fetched before FU-14 (2026-09-30) lacked"
  echo "#     the tag, Horizons read them as UT, and every row carried a dT-sized offset (about 38\""
  echo "#     for the Moon at 2050, 2-5\" for the Sun and inner planets). Those offsets were what the"
  echo "#     former 40.8\" Moon and 4-7\" Sun/Mercury/Venus/Mars tolerances absorbed."
  echo "#   - Sun: apparent corrections (precession, nutation, annual aberration) applied ONCE"
  echo "#     via apparent_sun_position; for the geocentric Sun light-time and annual aberration"
  echo "#     are the same effect, so no separate light-time re-query is performed."
  echo "#   - Planets and Moon: the light-time re-query of the geocentric position carries annual"
  echo "#     aberration; no separate term is added (#93, 2026-09-30)."
  echo "#   - Tolerance = per-body max observed residual + 2\", rounded up to 0.1\". Maxima measured"
  echo "#     2026-09-30 against TT-tagged goldens: Sun 0.111\", Moon 0.109\", Mercury 0.114\","
  echo "#     Venus 0.107\", Mars 0.166\", Jupiter 0.114\", Saturn 0.131\", Uranus 0.251\","
  echo "#     Neptune 0.179\", Pluto 0.154\" (the packaged-ephemeris fit floor)."
  echo "#   - 433-Eros: EXCLUDED. The light-time iteration diverges or goes out of range at 4 of 5 epochs"
  echo "#     because Eros's packaged data covers a limited span and the apparent-mode iteration steps outside"
  echo "#     it. Apparent-mode validation of Eros is not supported with the current packaged backend."
  echo "#     (At J2000 the residual was 68 arcsec, also exceeding any reasonable tolerance.)"
  echo "#"
  echo "# EPOCHS: 2415025.5 = 1900-Jan-06 TT (5 days past coverage start to avoid light-time stepping"
  echo "# before data start); 2488065.5 = 2099-Dec-26 TT (4 days before coverage end for same reason)."
  echo "body,jd_tt,apparent_longitude_deg,tolerance_arcsec"
  for entry in $BODIES; do
    label="${entry%%:*}"; code="${entry##*:}"
    # Per-body tolerance = max observed residual + 2", rounded up to 0.1" (measured 2026-09-30, FU-14).
    case "$label" in
      Sun) tol=2.2 ;;
      Moon) tol=2.2 ;;
      Mercury) tol=2.2 ;;
      Venus) tol=2.2 ;;
      Mars) tol=2.2 ;;
      Jupiter) tol=2.2 ;;
      Saturn) tol=2.2 ;;
      Uranus) tol=2.3 ;;
      Neptune) tol=2.2 ;;
      Pluto) tol=2.2 ;;
    esac
    for jd in $EPOCHS; do
      lon=$(fetch_tt "$code" "$jd" 31 | awk '{print $2}')
      echo "$label,$jd,$lon,$tol"
    done
  done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT"
