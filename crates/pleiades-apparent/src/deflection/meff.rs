/// Effective mass fraction for a ray passing at `r` solar radii; linear
/// between table rows (exact at a row), 0 at or below the centre and 1 at or
/// beyond the limb.
pub(crate) fn meff(r: f64) -> f64 {
    if r <= 0.0 {
        return 0.0;
    }
    if r >= 1.0 {
        return 1.0;
    }
    // First row with r_i <= r; the table starts at 1.0 > r, so i >= 1.
    let i = EFF_ARR
        .iter()
        .position(|&(ri, _)| ri <= r)
        .unwrap_or(EFF_ARR.len() - 1);
    let (r0, m0) = EFF_ARR[i - 1];
    let (r1, m1) = EFF_ARR[i];
    if r == r1 {
        // Return the row itself: the interpolation is not bit-exact there.
        return m1;
    }
    m0 + (r - r0) / (r1 - r0) * (m1 - m0)
}
